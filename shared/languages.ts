export function getLanguageName(code: string | undefined): string | undefined {
  if (!code) return undefined;
  return supportedLanguages.find((language) => language.code === code || language.code.split("-")[0] === code)?.name;
}

export function translationStorageKey(code: string): string {
  return `translation:${code}`;
}
